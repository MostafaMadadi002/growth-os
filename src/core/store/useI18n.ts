export const useI18n = create<I18nState>((set, get) => ({
  language: 'fa',
  dir: 'rtl',
  setLanguage: (lang) => set({ language: lang, dir: lang === 'fa' ? 'rtl' : 'ltr' }),
  t: (key) => {
    const lang = get().language;
    return (translations[lang] as any)[key] || key;
  }
}));
